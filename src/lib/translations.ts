export const translationMessages: { en: Record<TranslationKey, string> } & Record<
  Exclude<Locale, 'en'>,
  TranslationCatalog
> = { en, es, fr, de, it, pt, nl, ja, zh, ar, ru };

export const supportedLocales = Object.keys(translationMessages) as Locale[];

export function isSupportedLocale(value: unknown): value is Locale {
  return typeof value === 'string' && value in translationMessages;
}

const normalizeToSupportedLocale = (languageTag: string): Locale | null => {
  const normalized = languageTag.toLowerCase();
  if (isSupportedLocale(normalized)) {
    return normalized;
  }

  const baseLanguage = normalized.split('-')[0];
  if (isSupportedLocale(baseLanguage)) {
    return baseLanguage;
  }

  return null;
};

export const getBrowserLocale = (): Locale => {
  if (typeof window === 'undefined') return defaultLocale;

  const browserLocales = window.navigator.languages.length > 0
    ? window.navigator.languages
    : [window.navigator.language];

  for (const browserLocale of browserLocales) {
    const matchedLocale = normalizeToSupportedLocale(browserLocale);
    if (matchedLocale) {
      return matchedLocale;
    }
  }

  return defaultLocale;
};

export const t = (locale: Locale, key: TranslationKey): string => {
  return translationMessages[locale]?.[key] ?? translationMessages[defaultLocale][key] ?? key;
};

/** Replaces `{placeholder}` tokens in a translated message with concrete values. */
export function formatMessage(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (message, [key, value]) => message.split(`{${key}}`).join(String(value)),
    template,
  );
}
